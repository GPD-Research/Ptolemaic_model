"""Build Ptolemy's star catalogue (Almagest VII.5-VIII.1) from the CDS machine-readable edition.

Source: Verbunt & van Gent 2012, A&A 544, A31 (CDS J/A+A/544/A31, file ptolema.dat), based on
Toomer's edition, with Hipparcos identifications. Writes data/ptolemy_star_catalogue.csv and the
viewer's copy, viewer/stars.js.

    python tools/build_star_catalogue.py            # download, write both files
    python tools/build_star_catalogue.py FILE       # use a local ptolema.dat
    python tools/build_star_catalogue.py --check    # fail if viewer/stars.js is out of date
"""

import csv
import io
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "data" / "ptolemy_star_catalogue.csv"
JS_PATH = ROOT / "viewer" / "stars.js"
DESCRIPTIONS_PATH = ROOT / "data" / "ptolemy_star_descriptions.csv"
URL = "https://cdsarc.cds.unistra.fr/ftp/J/A+A/544/A31/ptolema.dat"

FIELDS = [
    "number", "constellation", "index", "outside", "lon_sign", "lon_deg", "lon_min",
    "lat_deg", "lat_min", "lat_dir", "magnitude", "qualifier", "hip", "id_quality",
    "vmag", "d_lon_arcmin", "d_lat_arcmin", "dist_arcmin",
]  # fmt: skip

# Byte ranges (1-based, inclusive) from the CDS ReadMe.
COLUMNS = {
    "number": (1, 4), "constellation": (9, 12), "index": (14, 15), "outside": (16, 16),
    "lon_sign": (19, 20), "lon_deg": (22, 23), "lon_min": (25, 26), "lat_deg": (29, 30),
    "lat_min": (32, 33), "lat_dir": (35, 35), "magnitude": (38, 38), "qualifier": (39, 39),
    "hip": (41, 46), "id_quality": (48, 48), "vmag": (52, 55), "d_lon_arcmin": (57, 62),
    "d_lat_arcmin": (64, 69), "dist_arcmin": (71, 76),
}  # fmt: skip

HEADER = (
    "// Generated by tools/build_star_catalogue.py from data/ptolemy_star_catalogue.csv; "
    "do not edit.\n"
    "// Ptolemy's star catalogue (Almagest VII.5-VIII.1), machine-readable edition of\n"
    "// Verbunt & van Gent 2012, A&A 544, A31 (CDS J/A+A/544/A31), after Toomer's edition.\n"
    "// Row: [number, constellation, index in it, longitude (arcmin), latitude (arcmin),\n"
    "//       magnitude (7 = faint, 9 = nebulous), qualifier (b/f), Hipparcos no.,\n"
    "//       V mag, dLon, dLat (arcmin, Hipparcos - Ptolemy at equinox -128),\n"
    "//       Latin description (Baily 1843), English gloss]\n"
)


def parse(text):
    rows = []
    for line in text.splitlines():
        if not line.strip():
            continue
        line = line.ljust(78)
        row = {k: line[a - 1 : b].strip() for k, (a, b) in COLUMNS.items()}
        row["constellation"] = row["constellation"].lstrip("=")
        rows.append(row)
    return rows


def read_csv():
    with CSV_PATH.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def read_descriptions():
    with DESCRIPTIONS_PATH.open(newline="", encoding="utf-8") as f:
        return {r["number"]: (r["latin"], r["english"]) for r in csv.DictReader(f)}


def js_rows(rows):
    words = read_descriptions()
    out = []
    for r in rows:
        lon = (int(r["lon_sign"]) - 1) * 1800 + int(r["lon_deg"]) * 60 + int(r["lon_min"])
        lat = int(r["lat_deg"]) * 60 + int(r["lat_min"])
        hip = int(r["hip"] or 0)
        out.append(
            [
                int(r["number"]), r["constellation"], int(r["index"]), lon,
                -lat if r["lat_dir"] == "A" else lat, int(r["magnitude"]), r["qualifier"],
                hip, float(r["vmag"]) if hip else None,
                float(r["d_lon_arcmin"]) if hip else None,
                float(r["d_lat_arcmin"]) if hip else None, *words[r["number"]],
            ]
        )  # fmt: skip
    return out


def render_js(rows):
    body = ",\n".join(json.dumps(r, ensure_ascii=False) for r in js_rows(rows))
    return (
        HEADER
        + "(function (root) {\n  const rows = [\n"
        + body
        + "\n  ];\n"
        + '  if (typeof module !== "undefined" && module.exports) module.exports = rows;\n'
        + "  else root.PtolemyStars = rows;\n})(this);\n"
    )


def main(argv):
    if argv[:1] == ["--check"]:
        if JS_PATH.read_text(encoding="utf-8") != render_js(read_csv()):
            sys.exit("viewer/stars.js is out of date: run python tools/build_star_catalogue.py")
        return
    if argv:
        text = Path(argv[0]).read_text(encoding="latin-1")
    else:
        text = urllib.request.urlopen(URL, timeout=60).read().decode("latin-1")
    rows = parse(text)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=FIELDS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    CSV_PATH.write_text(buf.getvalue(), encoding="utf-8")
    JS_PATH.write_text(render_js(rows), encoding="utf-8")
    print(f"{len(rows)} entries -> {CSV_PATH.relative_to(ROOT)}, {JS_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1:])
