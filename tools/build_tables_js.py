"""Write viewer/tables.js from Ptolemy's latitude tables in data/ (Almagest XIII.5).

python tools/build_tables_js.py          # write the file
python tools/build_tables_js.py --check  # exit 1 if it is stale
"""

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JS_PATH = ROOT / "viewer" / "tables.js"
SOURCES = ["ptolemy_latitude_tables.csv", "ptolemy_latitude_interpolation.csv"]


def read(name):
    with (ROOT / "data" / name).open(newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    return {"header": rows[0], "rows": rows[1:]}


def render():
    data = {name.removesuffix(".csv"): read(name) for name in SOURCES}
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return (
        "// Generated by tools/build_tables_js.py from data/*.csv; do not edit.\n"
        "// Ptolemy's latitude tables (Almagest XIII.5),"
        " after Van Brummelen 1993, Tables 14.2-14.13.\n"
        f"(function (root) {{\n  const data = {body};\n"
        '  if (typeof module !== "undefined" && module.exports) module.exports = data;\n'
        "  else root.TABLES = data;\n})(this);\n"
    )


def main():
    text = render()
    if "--check" in sys.argv:
        if JS_PATH.read_text(encoding="utf-8") != text:
            sys.exit(f"{JS_PATH.relative_to(ROOT)} is stale: run python tools/build_tables_js.py")
        return
    JS_PATH.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
